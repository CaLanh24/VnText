"""Headless Ren'Py runtime smoke of the generated Vietnamese font replacement (synthetic fixture, managed SDK, no user game).

usage: renpy_font_replacement_smoke.py <new_work_dir> <sdk_dir> <evidence_json>

Builds a tiny project with a Latin-only "Gothic.ttf" (a cmap-only font FreeType cannot load), the product overlay generated by ``prepare_font_support`` and
the product activation, runs the real Ren'Py 8.5.x with the dummy SDL driver and the software renderer, and records what ``config.font_replacement_map`` and
the engine's own ``renpy.text.font.get_font`` do.  A control project without the overlay must fail to load the same font.
"""
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tests.unit.test_renpy_font_lacking_vietnamese import LATIN, sfnt  # noqa: E402
from vntext.patch_renpy import _render_activation  # noqa: E402
from vntext.renpy_font_support import prepare_font_support  # noqa: E402

SCRIPT = '''init python:
    config.font_replacement_map["DejaVuSans.ttf", True, False] = ("DejaVuSans-Bold.ttf", False, False)

label start:
    python:
        import json
        import renpy.text.font as _font
        out = {"language": renpy.game.preferences.language, "class": type(config.font_replacement_map).__name__}
        for fn in ("fonts/Gothic.ttf", "Gothic.ttf", "GOTHIC.TTF", "./fonts/gothic.ttf", "fonts/Other.ttf", "DejaVuSans.ttf"):
            for b in (False, True):
                for i in (False, True):
                    out["%s|%s|%s" % (fn, b, i)] = list(config.font_replacement_map.get((fn, b, i), (fn, b, i)))
        try:
            fo = _font.get_font("Gothic.ttf", 24, False, False, 0, True, False, True, 1.0, "freetype", None, None, None)
            out["get_font"] = type(fo).__name__
        except Exception as exc:
            out["get_font_error"] = repr(exc)[:160]
        with open(renpy.config.basedir + "/smoke-out.json", "w") as handle:
            json.dump(out, handle, sort_keys=True)
    $ renpy.quit()
'''


def run(project: Path, sdk: Path) -> dict:
    env = dict(os.environ, SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy", RENPY_RENDERER="sw")
    process = subprocess.Popen([str(sdk / "lib/py3-windows-x86_64/python.exe"), "-B", str(sdk / "renpy.py"), str(project)], cwd=sdk, env=env,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, creationflags=0x08000000)
    try:
        process.wait(timeout=150)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait()
        raise SystemExit("Ren'Py smoke timed out")
    return json.loads((project / "smoke-out.json").read_text(encoding="utf-8"))


def build(project: Path, overlay: bool) -> None:
    (project / "game/fonts").mkdir(parents=True)
    (project / "game/fonts/Gothic.ttf").write_bytes(sfnt(LATIN))
    (project / "game/options.rpy").write_text("define config.save_directory = None\ndefine config.developer = True\n", encoding="utf-8")
    (project / "game/script.rpy").write_text(SCRIPT, encoding="utf-8")
    if overlay:
        bundled = ROOT / "vntext/fonts/DejaVuSans.ttf"
        digest = hashlib.sha256(bundled.read_bytes()).hexdigest()
        (project / "game/tl/vietnamese").mkdir(parents=True)
        (project / f"game/tl/vietnamese/vntext_font_{digest[:16]}.ttf").write_bytes(bundled.read_bytes())
        (project / "game/tl/vietnamese/vntext.rpy").write_text(prepare_font_support(project, {}, {}, bundled), encoding="utf-8")
        (project / "game/zzz_vntext_vietnamese.rpy").write_text(_render_activation(), encoding="utf-8")


def main() -> int:
    work, sdk, evidence = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve(), Path(sys.argv[3])
    work.mkdir(parents=True)
    build(work / "patched", True)
    build(work / "control", False)
    patched, control = run(work / "patched", sdk), run(work / "control", sdk)
    target = "tl/vietnamese/vntext_font_3fdf69cabf06049e.ttf"
    checks = {
        "language_active": patched["language"] == "vietnamese",
        "map_installed": patched["class"] == "_VNTextFontMap",
        "all_spellings_and_flags": all(patched[f"{fn}|{b}|{i}"] == [target, b, i] for fn in ("fonts/Gothic.ttf", "Gothic.ttf", "GOTHIC.TTF", "./fonts/gothic.ttf") for b in (False, True) for i in (False, True)),
        "other_font_untouched": all(patched[f"fonts/Other.ttf|{b}|{i}"] == ["fonts/Other.ttf", b, i] for b in (False, True) for i in (False, True)),
        "games_own_bold_entry_kept": patched["DejaVuSans.ttf|True|False"] == ["DejaVuSans-Bold.ttf", False, False],
        "engine_get_font_loads_replacement": patched.get("get_font") == "FTFont",
        "control_cannot_load_original": "get_font_error" in control and control["class"] == "dict",
    }
    result = {"checks": checks, "PASS": all(checks.values()), "patched": {k: patched.get(k) for k in ("language", "class", "get_font", "get_font_error")}, "control": {k: control.get(k) for k in ("class", "get_font", "get_font_error")}}
    evidence.write_text(json.dumps(result, indent=1), encoding="utf-8")
    print(json.dumps(result))
    return 0 if result["PASS"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
