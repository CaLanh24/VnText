from vntext.renpy_markup import overlay_problems

OVERLAY = """# Generated by VNText Studio. Do not edit native IDs.

translate vietnamese start_a:
    # "Hello"
    "Xin chào"

translate vietnamese start_b:
    # "Bye [name]"
    "Tạm biệt [tên"

translate vietnamese strings:
    old "Open"
    new "Mở"
    old "Close [x"
    new "Đóng [x"
    old "Save"
    new "Lưu"
"""

TRACEBACK = """I'm sorry, but an uncaught exception occurred.

While running game code:
  File "game/script.rpy", line 40, in script
  File "game/tl/vietnamese/vntext.rpy", line 9, in <module>
Exception: String 'Tạm biệt [tên' ends with an open format operation.

-- Full Traceback ------------------------------------------------------------

Full traceback:
  File "renpy/bootstrap.py", line 1, in bootstrap

Windows-10 AMD64
Ren'Py 8.5.2.26010301
"""


def _game(base: Path) -> Path:
    game = base / "gamecopy"
    (game / "game/tl/vietnamese").mkdir(parents=True)
    (game / "game/tl/vietnamese/vntext.rpy").write_text(OVERLAY, encoding="utf-8")
    (game / "traceback.txt").write_text(TRACEBACK, encoding="utf-8")
    return game


class GameErrorReport(unittest.TestCase):
    def test_traceback_is_parsed_without_keeping_text(self):
        parsed = parse_traceback(TRACEBACK)
        self.assertEqual("markup_open_bracket", parsed["kind"])
        self.assertEqual("8.5.2", parsed["renpy_version"][:5])
        self.assertEqual([9], parsed["overlay_lines"])

    def test_scan_finds_every_broken_line_and_the_unit_of_the_traceback(self):
        with tempfile.TemporaryDirectory() as temp:
            game = _game(Path(temp))
            result = scan_game(game)
            self.assertTrue(result["revertable"])
            self.assertEqual(2, len(result["units"]))        # start_b block + the one broken string pair
            text = json.dumps(result["report"], ensure_ascii=False)
            for secret in ("Tạm biệt", "Đóng", "gamecopy", "Hello"):
                self.assertNotIn(secret, text)               # anonymous: no sentence, no folder name
            self.assertTrue(any("dòng" in line for line in result["lines"]))

    def test_revert_removes_only_the_broken_units_and_keeps_a_backup(self):
        with tempfile.TemporaryDirectory() as temp:
            game = _game(Path(temp))
            result = scan_game(game)
            done = revert_units(game, [u["block"] for u in result["units"]])
            overlay = (game / "game/tl/vietnamese/vntext.rpy").read_text(encoding="utf-8")
            self.assertEqual([], overlay_problems(overlay))
            self.assertEqual([], done["remaining_problems"])
            self.assertIn('new "Mở"', overlay)               # unrelated strings stay
            self.assertIn('new "Lưu"', overlay)
            self.assertIn("Xin chào", overlay)
            self.assertNotIn("Tạm biệt", overlay)
            self.assertTrue(Path(done["backup"]).is_file())

    def test_no_traceback_and_clean_overlay_says_so(self):
        with tempfile.TemporaryDirectory() as temp:
            game = Path(temp) / "g"
            (game / "game/tl/vietnamese").mkdir(parents=True)
            (game / "game/tl/vietnamese/vntext.rpy").write_text('translate vietnamese start_a:\n    "Ổn"\n', encoding="utf-8")
            self.assertIsNone(find_traceback(game))
            self.assertFalse(scan_game(game)["revertable"])

    def test_cli_scan_and_revert(self):
        with tempfile.TemporaryDirectory() as temp:
            game = _game(Path(temp))
            scanned = bug_report_cli.run({"action": "game_error_scan", "src": str(game)})
            self.assertTrue(scanned["ok"] and scanned["revertable"])
            reverted = bug_report_cli.run({"action": "game_error_revert", "src": str(game), "blocks": scanned["blocks"]})
            self.assertTrue(reverted["ok"], reverted)


class SavedPathAndStatistics(unittest.TestCase):
    def test_bug_package_message_names_the_saved_file(self):
        with tempfile.TemporaryDirectory() as temp:
            game = _game(Path(temp))
            out = Path(temp) / "bug-reports"
            for flag in (True, False):
                result = bug_report_cli.run({"src": str(game), "out": str(out), "for_send": flag, "game_error": True})
                self.assertTrue(result["ok"], result)
                self.assertIn("Gói cũng được lưu tại " + result["path"], result["summary"])
            with zipfile.ZipFile(result["path"]) as archive:
                report = json.loads(archive.read("report.json"))
            self.assertEqual("markup_open_bracket", report["game_error"]["kind"])
            self.assertNotIn("Tạm biệt", json.dumps(report, ensure_ascii=False))

    def test_patch_statistics_name_each_reason_in_vietnamese(self):
        with tempfile.TemporaryDirectory() as temp:
            base = Path(temp)
            helper = PatchWritesNothingBroken()
            game, csv, manifest = helper._package(base, MarkupChecker.BROKEN)
            apply_renpy_translation_package(str(csv), str(manifest), str(game), str(base / "out"))
            (base / "extract_status.json").write_text(json.dumps({"skipped": 4, "excluded_engine_common": 2, "user_excluded": 1, "native_units": 9}), encoding="utf-8")
            report = write_patch_report(base / "out", base / "extract_status.json")
            self.assertEqual(1, report["patched"])
            self.assertEqual(1, report["repaired_markup"])
            text = "\n".join(report["lines"])
            self.assertIn("Đã Việt hóa: 1 câu", text)
            self.assertIn("4 mục", text)
            self.assertIn("engine Ren'Py", text)
            self.assertTrue((base / "out" / "bao_cao_viet_hoa.txt").is_file())

    def test_patch_statistics_blocked_reason(self):
        report = {"patched": 5, "kept_english_in_patch": {"chưa dịch": 3, "bị chặn vì dấu [ ] hoặc thẻ { } hỏng (game sẽ báo lỗi)": 2}, "left_out_before_patch": {}}
        lines = format_patch_report_vi(report)
        self.assertIn("Còn tiếng Anh vì chưa đủ điều kiện ghi vào game: 5 câu.", lines)
        self.assertTrue(any("3 câu chưa dịch" in line for line in lines))
        self.assertTrue(any("2 câu bị chặn" in line for line in lines))


