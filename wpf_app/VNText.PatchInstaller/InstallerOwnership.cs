using System.IO;
using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace VNText.PatchInstaller;

/// <summary>One layer of VNText ownership of a game file: which patch wrote it and the exact bytes it wrote.</summary>
public sealed class ReceiptLayer
{
    [JsonPropertyName("patch_id")] public string PatchId { get; set; } = "";
    [JsonPropertyName("version")] public string Version { get; set; } = "";
    [JsonPropertyName("installed_sha256")] public string InstalledSha256 { get; set; } = "";
}

/// <summary>The first state of one path before VNText ever touched it, plus the stack of VNText layers written on top of it.</summary>
public sealed class ReceiptEntry
{
    [JsonPropertyName("kind")] public string Kind { get; set; } = "file";
    [JsonPropertyName("first_original_exists")] public bool FirstOriginalExists { get; set; }
    [JsonPropertyName("first_original_sha256")] public string FirstOriginalSha256 { get; set; } = "";
    /// <summary>clean = the path did not exist; unmanaged_existing = a file we did not write (kept byte-for-byte);
    /// legacy_vntext_unreceipted = a VNText overlay installed by a release that kept no game-side receipt (NOT a clean original).</summary>
    [JsonPropertyName("provenance")] public string Provenance { get; set; } = "clean";
    [JsonPropertyName("layers")] public List<ReceiptLayer> Layers { get; set; } = new();
    [JsonPropertyName("source_digests")] public List<string> SourceDigests { get; set; } = new();
}

public sealed class OwnershipReceipt
{
    [JsonPropertyName("format")] public int Format { get; set; } = 1;
    [JsonPropertyName("game_root")] public string GameRoot { get; set; } = "";
    [JsonPropertyName("paths")] public Dictionary<string, ReceiptEntry> Paths { get; set; } = new(StringComparer.OrdinalIgnoreCase);
}

public enum UninstallMode
{
    /// <summary>Put back exactly what this install replaced (for an upgrade that is the previous VNText payload).</summary>
    Previous,
    /// <summary>Put back the first original recorded in the ownership receipt, removing every VNText layer.</summary>
    CleanOriginal,
}

public sealed record UninstallResult(List<string> Notes);

public sealed partial class InstallerService
{
    private const string ReceiptDirectoryName = ".vntext";
    private static readonly string[] VnTextMarkers = { "# VNText language-scoped", "# Generated by VNText Studio" };

    private static string ReceiptDirectory(string root) => Path.Combine(root, ReceiptDirectoryName);
    private static string ReceiptPath(string root) => Path.Combine(ReceiptDirectory(root), "ownership.json");
    private static string OriginalsRoot(string root) => Path.Combine(ReceiptDirectory(root), "originals");

    private string PatchId() => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(ManifestPath))).ToLowerInvariant();

    private static OwnershipReceipt LoadReceipt(string root)
    {
        var path = ReceiptPath(root);
        if (!File.Exists(path)) return new OwnershipReceipt { GameRoot = root };
        OwnershipReceipt? receipt;
        try { receipt = JsonSerializer.Deserialize<OwnershipReceipt>(File.ReadAllText(path), JsonOptions); }
        catch (Exception ex) when (ex is JsonException or IOException)
        {
            throw new InvalidOperationException($"Biên nhận sở hữu của VNText ({ReceiptDirectoryName}/ownership.json) không đọc được; giữ nguyên để kiểm tra, không cài/gỡ khi chưa rõ bản gốc: {ex.Message}");
        }
        if (receipt is null || receipt.Format != 1 || receipt.Paths is null)
            throw new InvalidOperationException($"Biên nhận sở hữu của VNText ({ReceiptDirectoryName}/ownership.json) có định dạng không hỗ trợ; không cài/gỡ khi chưa rõ bản gốc.");
        receipt.Paths = new Dictionary<string, ReceiptEntry>(receipt.Paths, StringComparer.OrdinalIgnoreCase);
        return receipt;
    }

    private static void SaveReceipt(string root, OwnershipReceipt receipt)
    {
        if (receipt.Paths.Count == 0)
        {
            if (File.Exists(ReceiptPath(root))) File.Delete(ReceiptPath(root));
            TryDeleteEmpty(OriginalsRoot(root));
            TryDeleteEmpty(ReceiptDirectory(root));
            return;
        }
        Directory.CreateDirectory(ReceiptDirectory(root));
        WriteJsonAtomic(ReceiptPath(root), receipt);
    }

    private static void TryDeleteEmpty(string directory)
    {
        if (!Directory.Exists(directory)) return;
        foreach (var child in Directory.EnumerateDirectories(directory, "*", SearchOption.AllDirectories).OrderByDescending(d => d.Length))
            if (!Directory.EnumerateFileSystemEntries(child).Any()) Directory.Delete(child);
        if (!Directory.EnumerateFileSystemEntries(directory).Any()) Directory.Delete(directory);
    }

    private static bool LooksLikeVnTextOverlay(string path)
    {
        using var stream = File.OpenRead(path);
        var buffer = new byte[96];
        var read = stream.Read(buffer, 0, buffer.Length);
        var head = System.Text.Encoding.UTF8.GetString(buffer, 0, read).TrimStart('﻿');
        return VnTextMarkers.Any(marker => head.StartsWith(marker, StringComparison.Ordinal));
    }

    private static readonly string[] LegacyNamePrefixes = { "vntext_font_", "zzz_vntext_" };

    /// <summary>A file VNText releases write: by name (generated fonts, overlay, activation) or by the generator's header.  Says nothing about WHICH release or whether it is verified.</summary>
    private static bool LooksLikeVnTextFile(string path)
    {
        var name = Path.GetFileName(path);
        if (LegacyNamePrefixes.Any(prefix => name.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))) return true;
        return name.EndsWith(".rpy", StringComparison.OrdinalIgnoreCase) && LooksLikeVnTextOverlay(path);
    }

    /// <summary>
    /// VNText-looking files in the game's script/translation folders that no active receipt layer or patch file accounts for: typically an older release's generated font
    /// or overlay installed without any receipt.  They are reported, never changed - nothing proves who installed them or that they are safe to remove.
    /// </summary>
    private List<string> FindUnverifiedLeftovers(string root, IEnumerable<string> accountedPaths)
    {
        var accounted = new HashSet<string>(accountedPaths.Select(p => p.Replace('\\', '/')), StringComparer.OrdinalIgnoreCase);
        var receipt = LoadReceipt(root);
        foreach (var pair in receipt.Paths) if (pair.Value.Layers.Count > 0) accounted.Add(pair.Key.Replace('\\', '/'));
        var found = new List<string>();
        var gameDirectory = Path.Combine(root, "game");
        if (!Directory.Exists(gameDirectory)) return found;
        var options = new EnumerationOptions { RecurseSubdirectories = true, IgnoreInaccessible = true, AttributesToSkip = FileAttributes.ReparsePoint };
        foreach (var file in Directory.EnumerateFiles(gameDirectory, "*", options))
        {
            var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
            if (accounted.Contains(relative)) continue;
            var inTranslation = relative.StartsWith("game/tl/", StringComparison.OrdinalIgnoreCase) || Path.GetDirectoryName(relative)?.Replace('\\', '/') == "game";
            if (!inTranslation) continue;
            bool vntext;
            try { vntext = LooksLikeVnTextFile(file); } catch (IOException) { continue; }
            if (!vntext) continue;
            found.Add($"{relative} (sha256 {HashFile(file)[..12]}..., {new FileInfo(file).Length:N0} byte)");
            if (found.Count >= 40) break;
        }
        return found;
    }

    private static string LeftoverNote(IReadOnlyList<string> leftovers) => leftovers.Count == 0 ? ""
        : "CÒN LẠI trong game (giữ nguyên, không xác minh được ai cài hoặc có backup không; có thể là patch VNText cũ vẫn đang chạy và gây lỗi font): "
          + string.Join("; ", leftovers) + ". Muốn gỡ sạch, hãy gỡ bằng đúng patch đã cài chúng hoặc xác minh lại game.";

    /// <summary>Human-readable truth about who owns the files this patch would write (shown before installing and by the CLI).</summary>
    public List<string> DescribeOwnership(string gameRoot)
    {
        var root = NormalizeGameRoot(gameRoot);
        var notes = new List<string>();
        var manifest = LoadManifest();
        var receipt = LoadReceipt(root);
        foreach (var file in manifest.Files)
        {
            var target = ResolveSafe(root, file.Path);
            if (receipt.Paths.TryGetValue(file.Path, out var entry) && entry.Layers.Count > 0)
            {
                var top = entry.Layers[^1];
                notes.Add(File.Exists(target) && string.Equals(HashFile(target), top.InstalledSha256, StringComparison.OrdinalIgnoreCase)
                    ? $"{file.Path}: đang do patch VNText {top.Version} quản lý ({entry.Layers.Count} lớp); cài patch này là nâng cấp, bản gốc đầu tiên ({DescribeOriginal(entry)}) được giữ."
                    : $"{file.Path}: tệp do patch VNText {top.Version} quản lý đã bị sửa ngoài VNText; sẽ không cài chồng.");
            }
            else if (File.Exists(target))
            {
                notes.Add(LooksLikeVnTextOverlay(target)
                    ? $"{file.Path}: đã có bản Việt hóa VNText cũ không có biên nhận sở hữu; gỡ patch này chỉ đưa về đúng bản cũ đó (không chứng minh được game gốc sạch)."
                    : $"{file.Path}: đã có tệp không do VNText quản lý; tệp được giữ nguyên làm bản gốc và sẽ được khôi phục khi gỡ.");
            }
        }
        var leftovers = FindUnverifiedLeftovers(root, manifest.Files.Select(f => f.Path).Concat(manifest.Files.Select(f => f.Path + "c")));
        if (leftovers.Count > 0) notes.Add(LeftoverNote(leftovers).Replace("CÒN LẠI trong game", "Đang có sẵn trong game"));
        return notes.Distinct().ToList();
    }

    private static string DescribeOriginal(ReceiptEntry entry) => entry.FirstOriginalExists
        ? (entry.Provenance == "legacy_vntext_unreceipted" ? "bản Việt hóa cũ không có biên nhận" : "tệp có sẵn của game/người dùng")
        : "không có tệp này";

    /// <summary>Hash of the file as the receipt expects it, for a path owned by a different patch than <paramref name="patchId"/>; null when not applicable.</summary>
    private static ReceiptLayer? NewerOwner(OwnershipReceipt receipt, string path, string patchId)
    {
        if (!receipt.Paths.TryGetValue(path, out var entry) || entry.Layers.Count == 0) return null;
        var top = entry.Layers[^1];
        return string.Equals(top.PatchId, patchId, StringComparison.OrdinalIgnoreCase) ? null : top;
    }

    /// <summary>Records the first original of <paramref name="relative"/> (once) and pushes this patch as the newest layer.</summary>
    private ReceiptEntry Claim(string root, OwnershipReceipt receipt, string relative, string kind, string patchId, string version, string installedSha, List<string> createdOriginals, List<string> notes)
    {
        var target = ResolveSafe(root, relative);
        if (!receipt.Paths.TryGetValue(relative, out var entry))
        {
            var exists = File.Exists(target);
            entry = new ReceiptEntry { Kind = kind, FirstOriginalExists = exists, FirstOriginalSha256 = exists ? HashFile(target) : "" };
            entry.Provenance = !exists ? "clean" : kind == "file" && LooksLikeVnTextFile(target) ? "legacy_vntext_unreceipted" : "unmanaged_existing";
            if (exists)
            {
                var keep = ResolveSafe(OriginalsRoot(root), relative);
                Directory.CreateDirectory(Path.GetDirectoryName(keep)!);
                File.Copy(target, keep, true);
                createdOriginals.Add(keep);
                if (kind == "file")
                    notes.Add(entry.Provenance == "legacy_vntext_unreceipted"
                        ? $"{relative}: bản Việt hóa VNText cũ không có biên nhận được giữ làm bản trước; gỡ chỉ đưa về bản đó, không phải game gốc sạch."
                        : $"{relative}: tệp có sẵn không do VNText quản lý được giữ nguyên làm bản gốc và sẽ được khôi phục khi gỡ.");
            }
            receipt.Paths[relative] = entry;
        }
        entry.Layers.Add(new ReceiptLayer { PatchId = patchId, Version = version, InstalledSha256 = installedSha });
        return entry;
    }

    private static void RemoveLayer(OwnershipReceipt receipt, string root, string relative, string patchId)
    {
        if (!receipt.Paths.TryGetValue(relative, out var entry)) return;
        entry.Layers.RemoveAll(layer => string.Equals(layer.PatchId, patchId, StringComparison.OrdinalIgnoreCase));
        if (entry.Layers.Count > 0) return;
        receipt.Paths.Remove(relative);
        var keep = ResolveSafe(OriginalsRoot(root), relative);
        if (File.Exists(keep)) File.Delete(keep);
    }

    /// <summary>Puts back the first original of every path this patch touched, proving each byte against the receipt, and drops all VNText layers.</summary>
    private UninstallResult RestoreCleanOriginal(string root, InstallState state, Action<string>? progress)
    {
        var receipt = LoadReceipt(root);
        var patchId = state.PatchId ?? "";
        var notes = new List<string>();
        var paths = state.Files.Select(f => f.Path).Concat((state.CompiledCaches ?? new List<CompiledCache>()).Select(c => c.Path)).ToList();
        foreach (var path in paths)
        {
            if (!receipt.Paths.TryGetValue(path, out var entry))
                throw new InvalidOperationException($"Không có biên nhận sở hữu cho {path}; không chứng minh được bản gốc sạch. Hãy dùng \"Gỡ cài đặt\" thông thường.");
            if (entry.Provenance == "legacy_vntext_unreceipted")
                throw new InvalidOperationException($"{path}: bản gốc đầu tiên là bản Việt hóa VNText cũ không có biên nhận, không phải game gốc sạch. Gỡ patch cũ sau khi gỡ patch này, hoặc xác minh lại game.");
            if (entry.Layers.Count == 0 || !string.Equals(entry.Layers[^1].PatchId, patchId, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException($"{path}: patch này không phải lớp VNText mới nhất; gỡ lớp mới nhất trước.");
            if (entry.FirstOriginalExists)
            {
                var keep = ResolveSafe(OriginalsRoot(root), path);
                if (!File.Exists(keep) || !string.Equals(HashFile(keep), entry.FirstOriginalSha256, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException($"Bản gốc đầu tiên của {path} thiếu hoặc đã bị thay đổi; không ghi vào game.");
            }
        }
        foreach (var path in paths)
        {
            progress?.Invoke(path);
            var entry = receipt.Paths[path];
            var target = ResolveSafe(root, path);
            if (entry.FirstOriginalExists)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                File.Copy(ResolveSafe(OriginalsRoot(root), path), target, true);
                if (!string.Equals(HashFile(target), entry.FirstOriginalSha256, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException($"Khôi phục bản gốc thất bại: {path}");
            }
            else if (File.Exists(target)) File.Delete(target);
            if (entry.Layers.Count > 1) notes.Add($"{path}: đã gỡ cả {entry.Layers.Count - 1} lớp patch cũ hơn; tệp trạng thái của chúng sẽ báo đã bị thay thế.");
            receipt.Paths.Remove(path);
            Fault("clean-restored:" + path);
        }
        // The first-original copies go only after the receipt no longer needs them: a restore cut off before this point can simply run again.
        SaveReceipt(root, receipt);
        Fault("clean-receipt-saved");
        foreach (var path in paths)
        {
            var originalKeep = ResolveSafe(OriginalsRoot(root), path);
            if (File.Exists(originalKeep)) File.Delete(originalKeep);
        }
        TryDeleteEmpty(OriginalsRoot(root)); TryDeleteEmpty(ReceiptDirectory(root));
        notes.Add("Đã về đúng bản gốc đầu tiên ghi trong biên nhận (hash đã khớp).");
        return new UninstallResult(notes);
    }

    /// <summary>True when the game's receipt holds VNText layers that a receipt-only clean restore could undo (no install state of this patch needed).</summary>
    public bool HasReceiptLayers(string gameRoot)
    {
        var root = NormalizeGameRoot(gameRoot);
        return Directory.Exists(root) && LoadReceipt(root).Paths.Values.Any(entry => entry.Layers.Count > 0);
    }

    /// <summary>
    /// Clean original from the game's receipt alone: used when the patch at hand is not the one installed (e.g. after uninstalling an upgrade the game holds the
    /// previous VNText patch, whose package was replaced).  Every VNText file must still be exactly the bytes of its newest layer (or already at its first original,
    /// when a previous run was cut off); otherwise nothing is written.  First-original copies are deleted only after the receipt is saved.
    /// </summary>
    private UninstallResult RestoreCleanOriginalFromReceipt(string gameRoot, Action<string>? progress)
    {
        var root = ValidateGameIdentity(gameRoot);
        var receipt = LoadReceipt(root);
        var paths = receipt.Paths.Where(pair => pair.Value.Layers.Count > 0).Select(pair => pair.Key).OrderBy(p => p, StringComparer.OrdinalIgnoreCase).ToList();
        if (paths.Count == 0)
            throw new InvalidOperationException("Game không có lớp patch VNText nào trong biên nhận; không còn gì để gỡ.");
        foreach (var path in paths)
        {
            var entry = receipt.Paths[path];
            var target = ResolveSafe(root, path);
            if (entry.Provenance == "legacy_vntext_unreceipted")
                throw new InvalidOperationException($"{path}: bản gốc đầu tiên là bản Việt hóa VNText cũ không có biên nhận, không phải game gốc sạch; game chưa bị thay đổi.");
            var atFirstOriginal = entry.FirstOriginalExists
                ? File.Exists(target) && string.Equals(HashFile(target), entry.FirstOriginalSha256, StringComparison.OrdinalIgnoreCase)
                : !File.Exists(target);
            // Compiled caches carry no installed hash (the engine may rebuild them); every other file must be exactly what the newest VNText layer wrote.
            var untouched = entry.Kind == "cache" || File.Exists(target)
                && string.Equals(HashFile(target), entry.Layers[^1].InstalledSha256, StringComparison.OrdinalIgnoreCase);
            if (!atFirstOriginal && !untouched)
                throw new InvalidOperationException($"{path}: tệp do patch VNText {entry.Layers[^1].Version} quản lý đã bị sửa ngoài VNText; không tự về bản gốc. Game chưa bị thay đổi.");
            if (entry.FirstOriginalExists)
            {
                var keep = ResolveSafe(OriginalsRoot(root), path);
                if (!File.Exists(keep) || !string.Equals(HashFile(keep), entry.FirstOriginalSha256, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException($"Bản gốc đầu tiên của {path} thiếu hoặc đã bị thay đổi; không ghi vào game.");
            }
        }
        var notes = new List<string>();
        var layers = paths.Max(path => receipt.Paths[path].Layers.Count);
        foreach (var path in paths)
        {
            progress?.Invoke(path);
            var entry = receipt.Paths[path];
            var target = ResolveSafe(root, path);
            if (entry.FirstOriginalExists)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                File.Copy(ResolveSafe(OriginalsRoot(root), path), target, true);
                if (!string.Equals(HashFile(target), entry.FirstOriginalSha256, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidOperationException($"Khôi phục bản gốc thất bại: {path}");
            }
            else if (File.Exists(target)) File.Delete(target);
            receipt.Paths.Remove(path);
            Fault("receipt-clean-restored:" + path);
        }
        SaveReceipt(root, receipt);
        Fault("receipt-clean-saved");
        foreach (var path in paths)
        {
            var originalKeep = ResolveSafe(OriginalsRoot(root), path);
            if (File.Exists(originalKeep)) File.Delete(originalKeep);
        }
        TryDeleteEmpty(OriginalsRoot(root)); TryDeleteEmpty(ReceiptDirectory(root));
        notes.Add($"Đã về đúng bản gốc đầu tiên ghi trong biên nhận cho {paths.Count} tệp (hash đã khớp), gỡ {layers} lớp patch VNText; tệp trạng thái của các patch cũ sẽ báo đã bị thay thế.");
        var leftovers = FindUnverifiedLeftovers(root, paths);
        if (leftovers.Count > 0) notes.Add(LeftoverNote(leftovers));
        return new UninstallResult(notes);
    }
